import math
import random
import colorsys
import pygame

pygame.init()
W, H = 720, 1280
screen = pygame.display.set_mode((W, H))
pygame.display.set_caption("Colorful Flower Explosion")
clock = pygame.time.Clock()
cx, cy = W // 2, H // 2
random.seed(12)

starts = [
    (random.randint(0, W), random.randint(0, H), random.randint(1, 10), random.randint(1, 10))
    for _ in range(100)
]
font = pygame.font.SysFont("consolas", 22, bold=True)
sub_font = pygame.font.SysFont("consolas", 15)
start_time = pygame.time.get_ticks()

def col(t):
    return tuple(int(v * 255) for v in colorsys.hsv_to_rgb(t % 1.0, 0.9, 0.85))

def curve(t, phase, scale, rotation):
    pts = []
    for i in range(361):
        a = math.tau * i / 360  
        r = ((math.sin(7 * a + phase) * 0.5 + math.cos(11 * a - phase)) * 0.5 + 1)
        r *= scale
        x = r * math.cos(a + rotation)
        y = r * math.sin(a + rotation)
        pts.append((cx + x, cy + y))
    return pts

running = True
while running:
    for event in pygame.event.get():
        if event.type == pygame.QUIT:
            running = False
            
    elapsed = pygame.time.get_ticks() - start_time
    t = elapsed / 1000
    progress = (elapsed % 10000) / 10000
    grow = min(1, progress * 4)
    screen.fill((4, 3, 18))
    
    # Draw background stars / dots
    for x, y, scale_val, rotation_val in starts:
        glow = 130 + int(100 * math.sin(t * 2 + x * 0.02) ** 2)
        pygame.draw.circle(screen, (glow // 2, glow // 2, glow), (x, y), max(1, scale_val // 3))
        
    rotation = t * 0.18
    
    # Draw layered curves
    for layer in range(9):
        scale = (25 + layer * 17) * grow
        phase = layer * 0.42 * t * 0.7
        pts = curve(t, phase, scale, rotation)
        if len(pts) > 2:
            pygame.draw.aalines(screen, col(t * 0.1 + layer * 0.05), True, pts)
            
    # Draw blooming polygon petals
    for i in range(28):
        phase = i * math.tau / 28
        pts = []
        for j in range(241):
            a = j / 240 * math.tau
            r = (65 + 45 * math.sin(6 * a + phase + t)) * grow
            x = cx + (r * math.cos(a + phase) * math.cos(phase) * 0.5 * grow)
            y = cy + (r * math.sin(a + phase) * math.sin(phase) * 0.5 * grow)
            pts.append((x, y))
        if len(pts) > 2:
            pygame.draw.polygon(screen, col(i / 20 + t * 0.08), pts, 1)
            
    # Draw center rings
    for ring in range(5):
        r_val = int((15 + ring * 12) * grow)
        pygame.draw.circle(screen, col(t * 0.1 + ring * 0.17), (cx, cy), r_val, 2)
       
    # Draw outer particle circles
    for i in range(28):  
        a = i * math.tau / 28 + rotation
        r_val = 210 * grow
        x = int(cx + r_val * math.cos(a))
        y = int(cy + r_val * math.sin(a))
        pygame.draw.circle(screen, col(i / 20 + t * 0.08), (x, y), 6)
        pygame.draw.circle(screen, (255, 255, 255), (x, y), 2)
         
    # Render UI Text
    title = font.render("cosmic flower", True, (210, 220, 255))
    subtitle = sub_font.render("GENERATED BY AI", True, (210, 220, 255))
    
    screen.blit(title, title.get_rect(center=(cx, 1050)))
    screen.blit(subtitle, subtitle.get_rect(center=(cx, 1085)))
    
    pygame.display.flip()
    clock.tick(30) 

pygame.quit()